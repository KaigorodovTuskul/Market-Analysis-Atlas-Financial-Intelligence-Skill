#!/usr/bin/env python3
"""Build 100 original standalone reference pages from curated data and SVG manifest."""
from __future__ import annotations
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SKILL=ROOT/'skills/market-analysis-atlas'
OUT=SKILL/'references/pattern-cards'
UPSIDE={
'Inverse Head and Shoulders','Double Bottom','Triple Bottom','Rounding Bottom','Cup and Handle','Ascending Triangle','Falling Wedge','Bull Flag','Bull Pennant','V Bottom','Spring (Wyckoff)','Golden Cross',
'Bullish Engulfing','Bullish Harami','Morning Star','Morning Doji Star','Three White Soldiers','Piercing Pattern','Tweezer Bottom','Bullish Abandoned Baby','Three Inside Up','Three Outside Up','Rising Three Methods',
}
DOWNSIDE={
'Head and Shoulders','Double Top','Triple Top','Rounding Top','Descending Triangle','Rising Wedge','Bear Flag','Bear Pennant','Diamond Top','V Top','Upthrust (Wyckoff)','Death Cross',
'Bearish Engulfing','Bearish Harami','Evening Star','Evening Doji Star','Three Black Crows','Dark Cloud Cover','Tweezer Top','Bearish Abandoned Baby','Three Inside Down','Three Outside Down','Falling Three Methods',
}
NEUTRAL={'Doji','Long-Legged Doji','Spinning Top','Inside Bar','Outside Bar','Harami Cross','Marubozu','Rectangle Range','Horizontal Channel','Symmetrical Triangle','Broadening Formation','Megaphone Pattern','Support Level','Resistance Level','Retest','False Breakout'}

def read_jsonl(path):return [json.loads(l) for l in path.read_text(encoding='utf-8').splitlines()]

def main():
    OUT.mkdir(parents=True,exist_ok=True)
    terms={e['id']:e for e in read_jsonl(SKILL/'data/terms.jsonl')}
    diagrams=json.loads((SKILL/'data/patterns.json').read_text(encoding='utf-8'))
    verified=json.loads((SKILL/'data/verified-links.json').read_text(encoding='utf-8'))['links']
    pages=[]
    for p in diagrams:
        e=terms[p['id']];term=e['term']
        if term in UPSIDE:direction='Conditional bullish setup'
        elif term in DOWNSIDE:direction='Conditional bearish setup'
        elif term in NEUTRAL:direction='Direction-neutral / context-dependent'
        else:direction='Context-dependent / alternative interpretations required'
        if e['category']=='candlesticks':
            evidence='Inspect open, high, low, close and the previous trend. Define real-body and wick ratios, gap policy and subsequent confirmation before assigning any signal.'
            failure='The candidate candle ratio is not met, the preceding trend is absent, or the next bars do not confirm the hypothesized change.'
        else:
            evidence='Mark price pivots with a fixed lookback and tolerance; draw any relevant level or boundary from completed bars; require a stated close/volume rule to confirm the proposed transition.'
            failure='Pivots fail the pre-specified geometry, price returns inside the invalidated boundary, or follow-through is absent within the chosen expiry window.'
        source=verified.get(e['id'],e['investopedia_index'])
        provenance='Verified direct secondary article link' if e['id'] in verified else 'General Investopedia alphabetic index; direct article not verified'
        md=f'''# {term}

**Category:** `{e['category']}` · **Reading:** {direction} · **Image type:** original synthetic schematic

![Synthetic schematic of {term}](../../assets/charts/{e['id']}.svg)

## Original short explanation

{e['definition']}

## Evidence to request

{evidence}

## Invalidation / alternative

{failure}

## Risk and method

{e['pitfall']}

The diagram is an original teaching illustration, **not actual price data**, not an Investopedia figure and not empirical evidence that trading the shape is profitable. Detection thresholds, liquidity, instrument, timeframe and transaction costs must be specified before claiming performance.

## Further navigation

[{provenance}]({source}). Article contents are **not reproduced**. See [chart-pattern protocol](../patterns.md) and [evidence requirements](../evidence.md).
'''
        filename=e['id']+'.md'
        (OUT/filename).write_text(md,encoding='utf-8')
        pages.append(f'- [{term}](pattern-cards/{filename}) — {direction}')
    index='''# Individual illustrated pattern cards

The following 100 cards pair **original, short educational definitions** with reproducible original SVG illustrations. They are not copied from or exhaustive of Investopedia, and they are not trading recommendations. This page is generated by `scripts/build_pages.py`.

'''+ '\n'.join(pages)+'\n'
    (SKILL/'references/pattern-index.md').write_text(index,encoding='utf-8')
    print('Generated',len(pages),'individual illustrated reference pages and pattern index')
if __name__=='__main__':main()
